/**
 * 실시간 검색 처리 함수 (input 이벤트)
 */
function handleSearch() {
    const query = searchInput.value.trim().toLowerCase();

    // 초기화 버튼 노출 여부
    if (searchInput.value.length > 0) {
        clearBtn.style.display = 'flex';
    } else {
        clearBtn.style.display = 'none';
    }

    // 대소문자 구분 없이 제목 또는 본문에 키워드가 포함된 카드 필터링
    let filteredData = DATA;
    if (query !== '') {
        filteredData = DATA.filter(item => {
            const titleMatch = item.title.toLowerCase().includes(query);
            const bodyMatch = item.body.toLowerCase().includes(query);
            return titleMatch || bodyMatch;
        });
    }

    renderCards(filteredData, query);
}

/**
 * 검색어 초기화 함수
 */
function clearSearch() {
    searchInput.value = '';
    clearBtn.style.display = 'none';
    searchInput.focus();
    renderCards(DATA);
}

/**
 * 카드 목록 렌더링 및 결과 건수 업데이트 함수
 * @param {Array} list - 표시할 데이터 배열
 * @param {string} query - 검색 키워드 (하이라이트용)
 */
function renderCards(list, query = '') {
    // 1. 표시 결과 건수 노출 ("결과 6건" / "결과 16건" 형태)
    resultCount.textContent = `결과 ${list.length}건`;

    // 2. 검색 결과가 0건일 때 안내 표시
    if (list.length === 0) {
        cardGrid.innerHTML = '';
        noResults.style.display = 'flex';
        return;
    }

    noResults.style.display = 'none';

    // 3. 카드 HTML 생성
    cardGrid.innerHTML = list.map(item => {
        const highlightedTitle = highlightKeyword(escapeHtml(item.title), query);
        const highlightedSummary = highlightKeyword(escapeHtml(item.summary), query);

        return `
            <article class="card" onclick="openModal(${item.id})" tabindex="0" role="button" aria-label="${escapeHtml(item.title)} 상세 보기" onkeydown="if(event.key==='Enter'||event.key===' ') { openModal(${item.id}); event.preventDefault(); }">
                <div class="card-header">
                    <span class="category-badge">${escapeHtml(item.category)}</span>
                    <span class="card-date">${escapeHtml(item.date)}</span>
                </div>
                <h3 class="card-title">${highlightedTitle}</h3>
                <p class="card-summary">${highlightedSummary}</p>
                <div class="card-footer">
                    <span class="view-detail-btn">
                        본문 보기
                        <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
                            <polyline points="9 18 15 12 9 6"></polyline>
                        </svg>
                    </span>
                </div>
            </article>
        `;
    }).join('');
}

/**
 * 검색 키워드 하이라이트 함수
 */
function highlightKeyword(text, keyword) {
    if (!keyword) return text;
    const re = new RegExp(`(${escapeRegExp(keyword)})`, 'gi');
    return text.replace(re, '<mark class="highlight">$1</mark>');
}

function escapeRegExp(string) {
    return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function escapeHtml(str) {
    if (!str) return '';
    return str
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#039;');
}

/**
 * 카드 클릭 시 본문 전문을 보는 모달 열기 함수 (가점 기능)
 * @param {number} id - 보도자료 ID
 */
function openModal(id) {
    const item = DATA.find(d => d.id === id);
    if (!item) return;

    modalTitle.textContent = item.title;
    modalDate.textContent = item.date;
    modalCategory.textContent = item.category;

    // 본문 문장 / 단락 구분 처리
    const cleanBody = item.body.trim();
    // 마침표 뒤 띄어쓰기를 기준으로 문단 분리
    const sentences = cleanBody.split(/(?<=\.)\s+/);
    
    // 3~4문장씩 묶어 문단 구성
    let paragraphs = [];
    let currentP = [];
    sentences.forEach((s, idx) => {
        currentP.push(s);
        if (currentP.length >= 3 || idx === sentences.length - 1) {
            paragraphs.push(currentP.join(' '));
            currentP = [];
        }
    });

    modalBody.innerHTML = paragraphs
        .map(p => `<p>${escapeHtml(p)}</p>`)
        .join('');

    modalOverlay.classList.add('active');
    document.body.style.overflow = 'hidden'; // 배경 스크롤 방지
    modalCloseBtn.focus();
}

/**
 * 모달 닫기 함수
 */
function closeModal() {
    modalOverlay.classList.remove('active');
    document.body.style.overflow = '';
}
